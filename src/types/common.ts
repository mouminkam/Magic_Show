/**
 * Cross-cutting primitives shared by every domain model and service response.
 *
 * The shapes mirror the Laravel API contract the storefront was originally
 * written against (`App\Http\Resources\*`), so swapping the mock service layer
 * for a real HTTP client is a drop-in change.
 */

/** Supported UI locales. */
export type Locale = "ar" | "en";

/** ISO-8601 timestamp, e.g. `2026-03-14T09:12:44.000Z`. */
export type IsoDateString = string;

/** Entity identifier. The backend uses auto-increment integers. */
export type EntityId = number;

/** Currency codes the storefront formats prices in. */
export type CurrencyCode = "SYP" | "USD" | "EUR" | "SAR";

/** Responsive image variants generated by the backend media pipeline. */
export interface ImageUrlSet {
  thumb: string;
  medium: string;
  full: string;
}

/** Envelope every successful service call resolves to. */
export interface ApiResponse<T> {
  success: true;
  data: T;
}

/** Page metadata returned alongside every paginated collection. */
export interface Pagination {
  currentPage: number;
  limit: number;
  totalItems: number;
  totalPages: number;
  hasNext: boolean;
  hasPrev: boolean;
}

/** Envelope for paginated collections. */
export interface PaginatedResponse<T> {
  success: true;
  data: { items: T[] };
  meta: { pagination: Pagination };
}

/** Inclusive numeric bounds, used for price filters. */
export interface NumericRange {
  min: number;
  max: number;
}

/** A `{ value, label }` pair for select/filter widgets. */
export interface SelectOption {
  value: string;
  label: string;
}

/**
 * Error thrown by the mock service layer. Mirrors the backend error envelope so
 * `apiErrorMessage()` can read it exactly as it read Axios errors.
 */
export class ApiError extends Error {
  readonly status: number;
  readonly code: string;
  readonly details?: Record<string, string[]>;
  /** Axios-compatible shape so existing error readers keep working. */
  readonly response: {
    status: number;
    data: {
      success: false;
      error: { code: string; message: string; details?: Record<string, string[]> };
    };
  };

  constructor(
    message: string,
    status = 400,
    code = "BAD_REQUEST",
    details?: Record<string, string[]>
  ) {
    super(message);
    this.name = "ApiError";
    this.status = status;
    this.code = code;
    this.details = details;
    this.response = {
      status,
      data: { success: false, error: { code, message, details } },
    };
  }
}
