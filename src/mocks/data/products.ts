/** Fixed reference date so mock timestamps are deterministic across renders. */
const CATALOG_EPOCH = Date.UTC(2026, 6, 20, 9, 0, 0);

function isoDaysAgo(days: number): string {
  return new Date(CATALOG_EPOCH - days * 86_400_000).toISOString();
}

function imageUrlSet(url: string) {
  // Public assets have no generated variants, so every size points at the
  // same file. A real backend returns three distinct URLs here.
  return { thumb: url, medium: url, full: url };
}

function buildImages(urls: string[], productName: string): ProductImage[] {
  return urls.map((url, index) => ({
    id: index === 0 ? null : index,
    url,
    imageUrls: imageUrlSet(url),
    altText: `${productName} — view ${index + 1}`,
    isPrimary: index === 0,
    order: index,
  }));
}

/**
 * Distributes a product's stock across every colour/size pair so variant
 * totals always add up to `stock`.
 */
function buildVariants(
  seed: ProductSeed,
  productColors: Color[],
  productSizes: Size[]
): ProductVariant[] {
  const pairs = productColors.flatMap((color) =>
    productSizes.map((size) => ({ color, size }))
  );
  if (pairs.length === 0) return [];

  const base = Math.floor(seed.stock / pairs.length);
  const remainder = seed.stock % pairs.length;

  return pairs.map((pair, index) => ({
    id: seed.id * 1000 + index,
    productId: seed.id,
    sku: `${seed.sku}-${pair.color.id}${pair.size.name}`,
    colorId: pair.color.id,
    sizeId: pair.size.id,
    stockQuantity: base + (index < remainder ? 1 : 0),
    priceModifier: 0,
  }));
}

function resolve<T>(ids: number[], index: Map<number, T>): T[] {
  return ids.map((id) => index.get(id)).filter((entity): entity is T => entity !== undefined);
}

function buildProduct(seed: ProductSeed): Product {
  const category = categories.find((c) => c.slug === seed.categorySlug);
  const productCategories = category
    ? category.parentSlug
      ? [category, ...categories.filter((c) => c.slug === category.parentSlug)]
      : [category]
    : [];

  const productColors = resolve<Color>(seed.colorIds, colorById);
  const productSizes = resolve<Size>(seed.sizeIds, sizeById);
  const productMaterials = resolve<Material>(seed.materialIds, materialById);
  const productSeasons = seed.seasons
    .map((value) => seasonByValue.get(value))
    .filter((season): season is Season => season !== undefined);

  const images = buildImages(seed.images, seed.name);
  const flags = seed.flags ?? [];
  const featuredImage = seed.images[0] ?? "https://images.unsplash.com/photo-1595950653106-6c9ebd614d3a?w=900&q=80&auto=format&fit=crop";

  return {
    id: seed.id,
    name: seed.name,
    slug: seed.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, ""),
    sku: seed.sku,
    description: seed.description,
    shortDescription: seed.shortDescription,
    price: seed.price,
    salePrice: seed.salePrice ?? null,
    currency: "USD",
    isFeatured: flags.includes("featured"),
    isActive: true,
    isNewArrival: flags.includes("new"),
    isBestSeller: flags.includes("bestseller"),
    categories: productCategories,
    brand: brandById.get(seed.brandId) ?? null,
    materials: productMaterials,
    images,
    featuredImage,
    featuredImageUrls: imageUrlSet(featuredImage),
    colors: productColors,
    sizes: productSizes,
    seasons: productSeasons,
    variants: buildVariants(seed, productColors, productSizes),
    stockQuantity: seed.stock,
    inStock: seed.stock > 0,
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    soldCount: seed.soldCount,
    weight: seed.weight ?? null,
    dimensions: null,
    createdAt: isoDaysAgo(seed.addedDaysAgo),
    updatedAt: isoDaysAgo(Math.max(0, seed.addedDaysAgo - 7)),
  };
}

/** The full catalogue: 44 products across 8 top-level categories. */
export const products: Product[] = productSeeds.map(buildProduct);

export const productById = new Map(products.map((p) => [p.id, p]));
